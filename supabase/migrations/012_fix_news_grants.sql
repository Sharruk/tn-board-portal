-- Migration 012 — Fix news_updates Table Privileges
-- TN State Board Student Portal
-- =============================================================================
--
-- ROOT CAUSE (identical to migration 009 for official_notices):
--   This Supabase project has had the default PUBLIC schema privilege revoked.
--   In standard PostgreSQL, CREATE TABLE implicitly grants access to the PUBLIC
--   role (which every role inherits). Supabase removes that grant by running
--   REVOKE ALL ON SCHEMA public FROM PUBLIC during project setup — a hardening
--   step that improves security but means every new table you create has ZERO
--   table-level privileges for `anon` and `authenticated` unless you add them
--   explicitly with GRANT statements.
--
--   PostgreSQL enforces TWO independent permission layers in sequence:
--     1. Table-level privileges  (GRANT SELECT ON …)
--     2. Row-Level Security      (RLS policies)
--   BOTH must be satisfied for a query to succeed. RLS alone is not enough;
--   if layer 1 fails, Postgres returns "permission denied for table …" before
--   it even checks RLS.
--
--   migration 011 correctly defined the RLS policies but omitted the explicit
--   GRANT statements — causing exactly the same error as official_notices.
--
-- WHY official_notices HAD THE SAME PROBLEM:
--   migration 008 (official_notices) also omitted GRANT statements, which
--   required the separate migration 009 (fix_notices_grants) to patch it.
--   The root cause is the same Supabase project-level setting on both tables.
--
-- THE FIX:
--   Explicitly GRANT the necessary table privileges:
--     anon         — SELECT only (public read, restricted by RLS)
--     authenticated — SELECT, INSERT, UPDATE, DELETE (admin, restricted by RLS)
--
--   news_updates uses UUID primary key generated by gen_random_uuid() so there
--   is NO sequence to grant (unlike official_notices which uses SERIAL).
--
-- RLS AUDIT:
--   The RLS policies in migration 011 are CORRECT and need no changes:
--     "news_public_select"  — restricts anon to published + published_at <= NOW()
--     "news_admin_all"      — gives authenticated full row access for admin CRUD
--
-- RPC / FUNCTION AUDIT:
--   Both RPCs defined in migration 011 already have GRANT EXECUTE:
--     increment_news_views(UUID)              — granted to anon, authenticated ✓
--     search_news(TEXT, TEXT, INTEGER)        — granted to anon, authenticated ✓
--   No additional GRANT EXECUTE statements are needed.
--
-- STORAGE AUDIT:
--   The four storage.objects policies for the "news-media" bucket cover:
--     SELECT  → public       (anon can read files)        ✓
--     INSERT  → authenticated (admin can upload)           ✓
--     UPDATE  → authenticated (admin can replace)          ✓
--     DELETE  → authenticated (admin can remove)           ✓
--   No additional storage grants are needed.
--
-- PREVENTION RULE FOR FUTURE MIGRATIONS:
--   Every new table created on this project MUST include these lines
--   immediately after CREATE TABLE:
--
--     GRANT SELECT                         ON <table> TO anon;
--     GRANT SELECT, INSERT, UPDATE, DELETE ON <table> TO authenticated;
--
--   If the table uses a SERIAL / SEQUENCE primary key, also add:
--     GRANT USAGE, SELECT ON SEQUENCE <table>_id_seq TO authenticated;
--
--   UUID primary keys (gen_random_uuid()) do NOT require sequence grants.
--
-- =============================================================================

-- ── Table privileges ──────────────────────────────────────────────────────────

-- anon: read-only (RLS further restricts to status='published' + published_at<=NOW())
GRANT SELECT ON news_updates TO anon;

-- authenticated: full CRUD (RLS allows all rows for admin users)
GRANT SELECT, INSERT, UPDATE, DELETE ON news_updates TO authenticated;

-- No sequence grant needed — UUID primary key uses gen_random_uuid(), not SERIAL.

